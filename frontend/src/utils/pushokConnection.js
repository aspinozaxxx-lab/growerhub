import { translateApp } from '../locales/i18n';

export function pushokError(code) {
  const messages = {
    PAIRING_REQUIRED: 'ПушОк не разрешил подключение. Дважды коротко нажмите кнопку сопряжения и повторите попытку.',
    CLOUD_UNAVAILABLE: 'Не удалось связаться с ПушОком. Проверьте питание шлюза, интернет и доступность в Управляторе.',
    HUB_IDENTITY_CHANGED: 'Ключ шлюза изменился. Если вы сбрасывали ПушОк, архивируйте это подключение и создайте новое.',
    HUB_COMMAND_REJECTED: 'Шлюз отклонил запрос. Проверьте обновления прошивки в Управляторе.',
    HUB_PROTOCOL_ERROR: 'Ответ шлюза пока не поддерживается. Напишите нам модель и версию прошивки.',
  };
  return translateApp(messages[code] || 'Не удалось подключить шлюз. Проверьте его ID и повторите попытку.');
}
